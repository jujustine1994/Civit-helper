import {build} from 'esbuild';
import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({absWorkingDir: root, entryPoints:['extension/page_source.mjs'],
  bundle:true,write:false,format:'iife',globalName:'CivitHelperPage',platform:'browser',
  target:'chrome120',legalComments:'inline'});
const output = '// Generated by npm run build; edit page_source.mjs.\n'
  + '// devalue is bundled under the MIT license; see DEVALUE-LICENSE.txt.\n'
  + 'export async function runPageCommand(cmd) {\n' + result.outputFiles[0].text
  + '\nreturn CivitHelperPage.execute(cmd);\n}\n';
await writeFile(new URL('../extension/page.mjs',import.meta.url),output);
await writeFile(new URL('../extension/DEVALUE-LICENSE.txt',import.meta.url),
  await readFile(new URL('../node_modules/devalue/LICENSE',import.meta.url)));
console.log('Built self-contained extension page decoder.');
